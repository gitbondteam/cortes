import type { CategoryId } from './categories';

/**
 * The catalogue.
 *
 * Every field is transcribed from "Catálogo de Cortes Argentinos - Precios".
 * Product photography is extracted from the same PDF — see CONTENT_NOTES.md.
 *
 * To add a product: drop `public/products/<slug>.webp` in place and append a
 * record below. Nothing else in the codebase needs to change.
 */
export interface Product {
  /** Stable identifier, mirrors the slug. */
  id: string;
  /** URL segment — ASCII only, so `/catalogo/<slug>/` stays portable. */
  slug: string;
  name: string;
  category: CategoryId;
  /** Packaging / weight exactly as offered, normalised for the web. */
  presentation?: string;
  /** Path under `public/`. */
  image: string;
  imageAlt: string;
  /** Price per kilo in ARS, from the catalogue. Hidden unless `site.catalog.showPrices`. */
  price?: number;
  priceUnit?: 'kg';
  featured?: boolean;
  /** Only ever set from source material — never invented marketing copy. */
  description?: string;
  tags?: string[];
}

